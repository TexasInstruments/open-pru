#endif

/*
 * MSRAM windows used by the host. They sit outside the memory regions of the
 * generated R5F linker command file (see generated/linker.cmd): the R5F image
 * lives below OUT_BASE, and USER_SHM_MEM/LOG_SHM_MEM (0x70150000..0x70158000
 * on AM261x) stay above the scan window. The 4 KB page at 0x70170000 is
 * left untouched on AM261x.
 */
#if defined(SOC_AM261X)
#define SHARED_END 0x18000U
#define OUT_BASE 0x70080000U
#define SCAN_MSRAM 0x700CC000U
#define SCAN_MSRAM_END 0x70150000U
#define OUT_LIMIT SCAN_MSRAM
#define TABLE_BASE 0x70171000U
#define TABLE_END 0x70180000U
#define BLOCK_COMP (TABLE_BASE + 0x1000U)
#define BLOCK_RST (TABLE_BASE + 0x3000U)
#define SEGMENTS (TABLE_BASE + 0x5000U)
#else
#define SHARED_END 0x20000U
#define OUT_BASE 0x700C0000U
#define SCAN_MSRAM 0x70120000U
#define SCAN_MSRAM_END 0x701D0000U
#define OUT_LIMIT TABLE_BASE
#define TABLE_BASE 0x70100000U
#define TABLE_END 0x70120000U
#define BLOCK_COMP (TABLE_BASE + 0x8000U)
#define BLOCK_RST (TABLE_BASE + 0xA000U)
#define SEGMENTS (TABLE_BASE + 0xC000U)
#endif
/* PRU core clock as configured in example.syscfg (250 MHz AM243x ICSSG, 225 MHz AM261x ICSSM). */
#define PRU_CLOCK_HZ CONFIG_PRU_ICSS0_CORE_CLK_FREQ_HZ
/* Global base of the PRU-ICSS instance the SysConfig CONFIG_PRU_ICSS0 handle refers to,
 * read from the driver so code and SysConfig cannot disagree. */
static uintptr_t gIcssBase;
#define ICSS_BASE gIcssBase
#if defined(SOC_AM261X)
#define SEC_ALLOC TABLE_BASE
#define SEC_END BLOCK_COMP
#else
#define SEC_ALLOC (TABLE_BASE + 0x10000U)
#define SEC_END TABLE_END
#endif

typedef struct {
    uint8_t id, h, v, tq, td, ta;
} Component;

typedef struct {
    uint8_t present;
    uint8_t bits[17];
    uint8_t value[256];
    uint16_t count;
} HuffTable;

typedef struct {
    uint16_t width, height, restart;
    uint8_t num_comp, max_h, max_v;
    Component comp[3];
    uint16_t qtab[2][64];
    uint8_t qpresent[2];
    HuffTable huff[2][2];
    uint32_t scan_addr;
    uint32_t scan_len;
    uint32_t segment[MAX_SEGMENTS][2];
    uint16_t num_segments;
    uint32_t blocks;
} JpegFrame;

static JpegFrame gFrame;
static const uint8_t gZigzag[64] = {
    0,1,8,16,9,2,3,10,17,24,32,25,18,11,4,5,
    12,19,26,33,40,48,41,34,27,20,13,6,7,14,21,28,35,
    42,49,56,57,50,43,36,29,22,15,23,30,37,44,51,58,
    59,52,45,38,31,39,46,53,60,61,54,47,55,62,63
};

static uint16_t be16(const uint8_t *p)
{
    return ((uint16_t)p[0] << 8) | p[1];
}

static void put8(uint32_t addr, uint8_t value)
{
    *(volatile uint8_t *)(uintptr_t)addr = value;
}

static void put16(uint32_t addr, uint16_t value)
{
    put8(addr, (uint8_t)value);
    put8(addr + 1U, (uint8_t)(value >> 8));
}

static void put32(uint32_t addr, uint32_t value)
{
    *(volatile uint32_t *)(uintptr_t)addr = value;
}

static uint32_t get32(uint32_t addr)
{
    return *(volatile uint32_t *)(uintptr_t)addr;
}

static void put_bytes(uint32_t addr, const uint8_t *data, uint32_t count)
{
    for (uint32_t i = 0; i < count; ++i) {
        put8(addr + i, data[i]);
    }
}

static int parse_scan(const uint8_t *data, size_t size, size_t pos)
{
    JpegFrame *f = &gFrame;
    uint32_t start = 0;
    uint32_t remaining = (uint32_t)(size - pos);
    f->scan_addr = remaining <= SHARED_END-SCAN_SHARED ? SCAN_SHARED : SCAN_MSRAM;
    if (f->scan_addr == SCAN_MSRAM && remaining > SCAN_MSRAM_END-SCAN_MSRAM) return -1;
    while (pos + 1U < size) {
        uint8_t b = data[pos++];
        if (b == 0xFFU) {
            uint8_t next = data[pos++];
            if (next == 0x00U) {
                b = 0xFFU;
            } else if (next >= 0xD0U && next <= 0xD7U) {
                if (f->restart == 0) return -1;
                if (f->num_segments >= MAX_SEGMENTS) return -1;
                f->segment[f->num_segments][0] = start;
                f->segment[f->num_segments++][1] = f->scan_len;
                start = f->scan_len;
                continue;
            } else if (next == 0xD9U) {
                if (f->num_segments >= MAX_SEGMENTS) return -1;
                f->segment[f->num_segments][0] = start;
                f->segment[f->num_segments++][1] = f->scan_len;
                return 0;
            } else {
                return -1;
            }
        }
        uint32_t limit = f->scan_addr == SCAN_SHARED ? SHARED_END : SCAN_MSRAM_END;
        if (f->scan_addr + f->scan_len >= limit) return -1;
        put8((f->scan_addr == SCAN_SHARED ? ICSS_BASE : 0U) + f->scan_addr + f->scan_len++, b);
    }
    return -1;
}

/* Parse one baseline, interleaved scan. Return a message for rejected input. */
static const char *parse_jpeg(const uint8_t *data, size_t size)
{
    JpegFrame *f = &gFrame;
    size_t pos = 2;
    uint8_t saw_sof = 0;
    memset(f, 0, sizeof(*f));
    if (size < 4 || data[0] != 0xFF || data[1] != 0xD8)
        return "missing SOI marker";
    while (pos + 3 < size) {
        if (data[pos++] != 0xFF) return "invalid marker boundary";
        while (pos < size && data[pos] == 0xFF) ++pos;
        if (pos >= size) return "truncated marker";
        uint8_t marker = data[pos++];
        if (marker == 0xD9) break;
        if (marker == 0x01 || (marker >= 0xD0 && marker <= 0xD7))
            return "unexpected marker before scan";
        if (pos + 2 > size) return "truncated segment length";
        uint16_t len = be16(data + pos);
        if (len < 2 || pos + len > size) return "invalid segment length";
        const uint8_t *p = data + pos + 2;
        size_t n = len - 2U;
        if (marker == 0xC2) return "progressive JPEG is unsupported";
        if (marker == 0xCC) return "arithmetic coding is unsupported";
        if ((marker >= 0xC0 && marker <= 0xCF) && marker != 0xC0 && marker != 0xC4 && marker != 0xCC)
            return "unsupported JPEG frame type";
        if (marker == 0xC0) {
            if (n < 6 || p[0] != 8 || p[5] == 0 || p[5] > 3 || n != 6U + 3U*p[5])
                return "unsupported frame header";
            f->height = be16(p + 1);
            f->width = be16(p + 3);
            f->num_comp = p[5];
            if (!f->width || !f->height || (f->num_comp != 1 && f->num_comp != 3))
                return "unsupported image dimensions or components";
            for (uint8_t i = 0; i < f->num_comp; ++i) {
                Component *c = &f->comp[i];
                c->id = p[6U + 3U*i];
                c->h = p[7U + 3U*i] >> 4;
                c->v = p[7U + 3U*i] & 15U;
                c->tq = p[8U + 3U*i];
                if (!c->h || !c->v || c->tq > 1) return "unsupported component sampling or quantization";
                if (c->h > f->max_h) f->max_h = c->h;
                if (c->v > f->max_v) f->max_v = c->v;
            }
            if (f->num_comp == 1) {
                if (f->max_h != 1 || f->max_v != 1)
                    return "unsupported grayscale sampling";
            } else if (f->max_h == 1 && f->max_v == 1) {
                for (uint8_t i = 0; i < 3; ++i)
                    if (f->comp[i].h != 1 || f->comp[i].v != 1)
                        return "unsupported 4:4:4 sampling";
            } else if (f->max_h == 2 && f->max_v == 2) {
                if (f->comp[0].h != 2 || f->comp[0].v != 2 ||
                    f->comp[1].h != 1 || f->comp[1].v != 1 ||
                    f->comp[2].h != 1 || f->comp[2].v != 1)
                    return "unsupported 4:2:0 sampling";
            } else {
                return "unsupported sampling (expected grayscale, 4:4:4, or 4:2:0)";
            }
            saw_sof = 1;
        } else if (marker == 0xDB) {
            for (size_t off = 0; off < n;) {
                uint8_t id = p[off++];
                if ((id >> 4) != 0 || (id & 15U) > 1 || off + 64 > n)
                    return "unsupported quantization table";
                for (uint32_t k = 0; k < 64; ++k)
                    f->qtab[id & 15U][gZigzag[k]] = p[off + k];
                f->qpresent[id & 15U] = 1;
                off += 64;
            }
        } else if (marker == 0xC4) {
            for (size_t off = 0; off < n;) {
                if (off + 17 > n) return "truncated Huffman table";
                uint8_t id = p[off++];
                if ((id >> 4) > 1 || (id & 15U) > 1) return "unsupported Huffman table id";
                HuffTable *t = &f->huff[id >> 4][id & 15U];
                uint32_t count = 0;
                for (uint32_t l = 1; l <= 16; ++l) {
                    t->bits[l] = p[off++];
                    count += t->bits[l];
                }
                if (count > 256 || off + count > n) return "invalid Huffman table";
                uint32_t code = 0, long_count = 0;
                for (uint32_t l = 1; l <= 16; ++l) {
                    if (code + t->bits[l] > (1U << l))
                        return "oversubscribed Huffman table";
                    if (l > 8) long_count += t->bits[l];
                    code = (code + t->bits[l]) << 1;
                }
                if (long_count > 255) return "Huffman long-code table is too large";
                for (uint32_t k = 0; k < count; ++k) {
                    uint8_t sym = p[off + k];
                    if ((id >> 4) == 0 ? sym > 11 :
                        ((sym & 15U) > 10 ||
                         ((sym & 15U) == 0 && sym != 0 && sym != 0xF0)))
                        return "unsupported Huffman symbol";
                }
                memcpy(t->value, p + off, count);
                t->count = (uint16_t)count;
                t->present = 1;
                off += count;
            }
        } else if (marker == 0xDD) {
            if (n != 2) return "invalid restart interval";
            f->restart = be16(p);
        } else if (marker == 0xDA) {
            if (!saw_sof || n != 1U + 2U*f->num_comp + 3U || p[0] != f->num_comp)
                return "unsupported scan structure";
            for (uint8_t i = 0; i < f->num_comp; ++i) {
                if (p[1U + 2U*i] != f->comp[i].id) return "component order is unsupported";
                uint8_t sel = p[2U + 2U*i];
                f->comp[i].td = sel >> 4;
                f->comp[i].ta = sel & 15U;
                if (f->comp[i].td > 1 || f->comp[i].ta > 1 ||
                    !f->huff[0][f->comp[i].td].present ||
                    !f->huff[1][f->comp[i].ta].present ||
                    !f->qpresent[f->comp[i].tq])
                    return "missing or unsupported scan table";
            }
            if (p[n-3] != 0 || p[n-2] != 63 || p[n-1] != 0)
                return "successive or spectral scan is unsupported";
            if (parse_scan(data, size, pos + len) != 0)
                return "invalid or oversized entropy scan";
            uint32_t mw = 8U*f->max_h, mh = 8U*f->max_v;
            uint32_t mcus = ((f->width + mw - 1U)/mw) * ((f->height + mh - 1U)/mh);
            uint32_t expected_segments = f->restart ?
                (mcus + f->restart - 1U) / f->restart : 1U;
            if (expected_segments > MAX_SEGMENTS ||
                f->num_segments != expected_segments)
                return "restart segment count does not match MCU count";
            uint32_t per_mcu = 0;
            for (uint8_t i = 0; i < f->num_comp; ++i)
                per_mcu += f->comp[i].h * f->comp[i].v;
            f->blocks = mcus * per_mcu;
            if (f->blocks == 0 || f->blocks > MAX_BLOCKS)
                return "image has too many blocks";
            return NULL;
        }
        pos += len;
    }
    return "missing baseline scan";
}

static uint32_t make_huffman(const HuffTable *t, uint32_t primary, uint32_t secondary)
{
    uint32_t code = 0, index = 0, nlong = 0;
    uint32_t mincode[17] = {0}, maxcode[17] = {0}, first[17] = {0};
    for (uint32_t i = 0; i < 512; ++i) put8(ICSS_BASE + primary + i, 0);
    for (uint32_t l = 1; l <= 16; ++l) {
        first[l] = nlong;
        mincode[l] = code;
        for (uint32_t j = 0; j < t->bits[l]; ++j) {
            uint8_t sym = t->value[index++];
            if (l <= 8) {
                uint32_t base = code << (8U-l), copies = 1U << (8U-l);
                for (uint32_t x = 0; x < copies; ++x) {
                    put8(ICSS_BASE + primary + (base+x)*2U, (uint8_t)(l << 4));
                    put8(ICSS_BASE + primary + (base+x)*2U + 1U, sym);
                }
            } else {
                uint32_t a = secondary + 4U + 4U*nlong++;
                put8(a, (uint8_t)l);
                put8(a+1U, sym);
                put16(a+2U, (uint16_t)(code << (16U-l)));
            }
            ++code;
        }
        maxcode[l] = code ? code - 1U : 0U;
        code <<= 1;
    }
    uint32_t table = 4U + 4U*nlong;
    put8(secondary, (uint8_t)nlong);
    put8(secondary+1U, 0);
    put16(secondary+2U, (uint16_t)table);
    for (uint32_t l = 9; l <= 16; ++l) {
        uint32_t addr = secondary + table + (l-9U)*8U;
        if (t->bits[l]) {
            put32(addr, (maxcode[l]+1U) << (16U-l));
            put32(addr+4U, 4U*(first[l]-mincode[l]));
        } else {
            put32(addr, 0);
            put32(addr+4U, 0);
        }
    }
    return (table + 64U + 3U) & ~3U;
}

static uint32_t crc32_memory(uint32_t addr, uint32_t count)
{
    uint32_t crc = ~0U;
    CacheP_inv((void *)(uintptr_t)addr, count, CacheP_TYPE_ALL);
    for (uint32_t i = 0; i < count; ++i) {
        crc ^= *(volatile uint8_t *)(uintptr_t)(addr+i);
        for (uint32_t b = 0; b < 8; ++b)
            crc = (crc >> 1) ^ (0xEDB88320U & (0U - (crc & 1U)));
    }
    return ~crc;
}

static const char *prepare_memory(void)
{
    JpegFrame *f = &gFrame;
    uint32_t scan_addr = f->scan_addr;
    if (OUT_BASE + 64U*f->blocks > OUT_LIMIT)
        return "output exceeds MSRAM window";
    if (BLOCK_COMP + f->blocks > TABLE_END ||
        BLOCK_RST + f->blocks > TABLE_END || SEGMENTS + 8U*f->num_segments > TABLE_END)
        return "metadata exceeds MSRAM window";
    uint32_t sec[2][2] = {{0}};
    uint32_t alloc = SEC_ALLOC;
    for (uint32_t kind = 0; kind < 2; ++kind) {
        for (uint32_t id = 0; id < 2; ++id) {
            if (!f->huff[kind][id].present) continue;
            uint32_t primary = (kind ? 0x440U : 0x40U) + id*0x200U;
            if (alloc + 1100U > SEC_END) return "Huffman tables exceed MSRAM";
            sec[kind][id] = alloc;
            alloc += make_huffman(&f->huff[kind][id], primary, alloc);
            if (alloc > SEC_END) return "Huffman tables exceed MSRAM";
        }
    }
    put_bytes(ICSS_BASE + ZIG_BASE, gZigzag, 64);
    for (uint32_t i = 0; i < f->num_comp; ++i) {
        Component *c = &f->comp[i];
        uint32_t a = ICSS_BASE + COMP_BASE + 16U*i;
        put32(a, (c->td ? 0x240U : 0x40U));
        put32(a+4U, (c->ta ? 0x640U : 0x440U));
        put32(a+8U, sec[0][c->td]);
        put32(a+12U, sec[1][c->ta]);
        for (uint32_t k = 0; k < 64; ++k)
            put16(ICSS_BASE + QTAB_BASE + 128U*i + 2U*k, f->qtab[c->tq][k]);
    }
    uint32_t block = 0;
    uint32_t mx_count = (f->width + 8U*f->max_h - 1U)/(8U*f->max_h);
    uint32_t my_count = (f->height + 8U*f->max_v - 1U)/(8U*f->max_v);
    for (uint32_t my = 0, mcu = 0; my < my_count; ++my) {
        for (uint32_t mx = 0; mx < mx_count; ++mx, ++mcu) {
            uint8_t first = 1;
            for (uint32_t ci = 0; ci < f->num_comp; ++ci) {
                Component *c = &f->comp[ci];
                for (uint32_t k = 0; k < c->h*c->v; ++k) {
                    put8(BLOCK_COMP + block, (uint8_t)ci);
                    put8(BLOCK_RST + block, (uint8_t)(first && mcu && f->restart && mcu%f->restart == 0));

                    first = 0;
                    ++block;
                }
            }
        }
    }
    for (uint32_t i = 0; i < f->num_segments; ++i) {
        put32(SEGMENTS + 8U*i, scan_addr + f->segment[i][0]);
        put32(SEGMENTS + 8U*i + 4U, scan_addr + f->segment[i][1]);
    }
    for (uint32_t i = 0; i < 64U*f->blocks; ++i) put8(OUT_BASE + i, 0xA5U);
    put32(ICSS_BASE + CTRL_BASE + 0U, scan_addr);
    put32(ICSS_BASE + CTRL_BASE + 4U, f->scan_len);
    put32(ICSS_BASE + CTRL_BASE + 8U, 0);
    put32(ICSS_BASE + CTRL_BASE + 12U, f->blocks);
    put32(ICSS_BASE + CTRL_BASE + 16U, 0);
    put32(ICSS_BASE + CTRL_BASE + 20U, BLOCK_COMP);
    put32(ICSS_BASE + CTRL_BASE + 24U, BLOCK_RST);
    put32(ICSS_BASE + CTRL_BASE + 28U, COMP_BASE);
    put32(ICSS_BASE + CTRL_BASE + 32U, 0x1400U);
    put32(ICSS_BASE + CTRL_BASE + 36U, ZIG_BASE);
    put32(ICSS_BASE + CTRL_BASE + 40U, SEGMENTS);
    put32(ICSS_BASE + CTRL_BASE + 48U, 0);
#if defined(JPEG_SINGLE_CORE)
    put32(ICSS_BASE + SC_OUTPTR, OUT_BASE);
#else
    put32(ICSS_BASE + P1_BASE + 0U, f->blocks);
    put32(ICSS_BASE + P1_BASE + 4U, 0);
    put32(ICSS_BASE + P1_BASE + 8U, OUT_BASE);
    put32(ICSS_BASE + P1_BASE + 12U, 0);
#endif
    CacheP_wb((void *)(uintptr_t)OUT_BASE, 64U*f->blocks, CacheP_TYPE_ALL);
    CacheP_wb((void *)(uintptr_t)TABLE_BASE, TABLE_END-TABLE_BASE, CacheP_TYPE_ALL);
    if (scan_addr == SCAN_MSRAM)
        CacheP_wb((void *)(uintptr_t)scan_addr, f->scan_len, CacheP_TYPE_ALL);
    return NULL;
}

static void run_image(PRUICSS_Handle handle, const JpegTestImage *image)
{
    gIcssBase = ((PRUICSS_HwAttrs const *)handle->hwAttrs)->baseAddr;
    int32_t status = PRUICSS_disableCore(handle, PRUICSS_PRU0);
    DebugP_assert(status == SystemP_SUCCESS);
    status = PRUICSS_disableCore(handle, PRUICSS_PRU1);
    DebugP_assert(status == SystemP_SUCCESS);
    /* The slot protocol uses fixed register positions, never R0 remapping.
     * Configuration may survive a core reset or a previous application. */
    uint32_t spp = (uint32_t)
        ((PRUICSS_HwAttrs const *)handle->hwAttrs)->cfgRegBase + CFG_SPP;
    uint32_t remap = get32(spp) & XFR_REMAP_MASK;
    if (remap != 0U)
        DebugP_log("Disabling scratchpad register remapping: %x\r\n", remap);
    put32(spp, get32(spp) & ~XFR_REMAP_MASK);
    const char *error = parse_jpeg(image->data, image->size);
    if (error) {
        DebugP_log("%s: %s\r\n", image->name, error);
        return;
    }
    DebugP_assert(PRUICSS_initMemory(handle, PRUICSS_DATARAM(PRUICSS_PRU0)) != 0U);
    DebugP_assert(PRUICSS_initMemory(handle, PRUICSS_DATARAM(PRUICSS_PRU1)) != 0U);
    error = prepare_memory();
    if (error) {
        DebugP_log("%s: %s\r\n", image->name, error);
        return;
    }
    status = PRUICSS_resetCore(handle, PRUICSS_PRU0);
    DebugP_assert(status == SystemP_SUCCESS);
    DebugP_assert(PRUICSS_writeMemory(handle, PRUICSS_IRAM_PRU(0), 0,
                  PRU0Firmware_0, sizeof(PRU0Firmware_0))*4U == sizeof(PRU0Firmware_0));
    /* The PRUICSS_writeMemory offset is in bytes (the driver adds it to the
     * memory base unscaled), so the stubs go to IRAM byte address 0x2F00. */
    DebugP_assert(PRUICSS_writeMemory(handle, PRUICSS_IRAM_PRU(0), START_STUB,
                  gStartPru0, sizeof(gStartPru0))*4U == sizeof(gStartPru0));
    /* Clear the CYCLE counter(s) while the core(s) are held in reset. */
    put32(ICSS_BASE + PRU0_CYCLE, 0);
#if !defined(JPEG_SINGLE_CORE)
    status = PRUICSS_resetCore(handle, PRUICSS_PRU1);
    DebugP_assert(status == SystemP_SUCCESS);
    DebugP_assert(PRUICSS_writeMemory(handle, PRUICSS_IRAM_PRU(1), 0,
                  PRU1Firmware_0, sizeof(PRU1Firmware_0))*4U == sizeof(PRU1Firmware_0));
    DebugP_assert(PRUICSS_writeMemory(handle, PRUICSS_IRAM_PRU(1), START_STUB,
                  gStartPru1, sizeof(gStartPru1))*4U == sizeof(gStartPru1));
    put32(ICSS_BASE + PRU1_CYCLE, 0);
#endif
    /*
     * CONTROL stages PCTR_RST_VAL and COUNTER_ENABLE while disabled;
     * PRUICSS_enableCore starts the core at the stub. In the dual
     * core build the host waits for PRU1 readiness before starting PRU0; in the single core build PRU1 stays disabled.
     *
     * COUNTER_ENABLE (bit 3) is set here, not only by the start stub: on ICSSM
     * (AM261x) the core starts on this write, so the stub's read-modify-write
     * of CONTROL races the read-modify-write inside PRUICSS_enableCore() below,
     * which then writes the enable bit back as clear. Measured on LP-AM261 in
     * the single core build: CONTROL read 0x0BC08003 while running and CYCLE
     * froze at 25. With the bit in this value, PRUICSS_enableCore() preserves it.
     */
    uint64_t began = ClockP_getTimeUsec();
#if !defined(JPEG_SINGLE_CORE)
    put32(ICSS_BASE + PRU1_CONTROL, (START_STUB/4U << 16) | 8U);
    status = PRUICSS_enableCore(handle, PRUICSS_PRU1);
    DebugP_assert(status == SystemP_SUCCESS);
    while (get32(ICSS_BASE + P1_BASE + 12U) != 1U) {
        if (ClockP_getTimeUsec() - began > JPEG_TIMEOUT_US) {
            DebugP_log("%s: PRU1 initialization timeout\r\n", image->name);
            goto stop;
        }
        ClockP_usleep(1);
    }
#endif
    put32(ICSS_BASE + PRU0_CONTROL, (START_STUB/4U << 16) | 8U);
    status = PRUICSS_enableCore(handle, PRUICSS_PRU0);
    DebugP_assert(status == SystemP_SUCCESS);
#if defined(JPEG_SINGLE_CORE)
    /*
     * Done: completion flag set and the output pointer advanced past the last
     * block. PRU0 halts without the completion flag on an entropy decode error.
     */
    const uint32_t out_end = OUT_BASE + 64U*gFrame.blocks;
    while (get32(ICSS_BASE + START_DONE) != 1U || get32(ICSS_BASE + SC_OUTPTR) != out_end ||
           (get32(ICSS_BASE + PRU0_CONTROL) & PRU_RUNSTATE) != 0U) {
        if ((get32(ICSS_BASE + PRU0_CONTROL) & PRU_RUNSTATE) == 0U) {
            if (get32(ICSS_BASE + START_DONE) == 1U && get32(ICSS_BASE + SC_OUTPTR) == out_end) break;
            DebugP_log("%s: entropy decode error %x\r\n", image->name,
                       *(volatile uint8_t *)(uintptr_t)(ICSS_BASE + DECODE_ERROR));
            goto stop;
        }
        if (ClockP_getTimeUsec() - began > JPEG_TIMEOUT_US) {
            DebugP_log("%s: timeout\r\n", image->name);
            goto stop;
        }
        ClockP_usleep(100);
    }
    uint32_t crc = crc32_memory(OUT_BASE, 64U*gFrame.blocks);
    uint32_t cycles = get32(ICSS_BASE + PRU0_CYCLE);
    uint32_t fps = cycles ? PRU_CLOCK_HZ / cycles : 0;
    DebugP_log("%s: CRC %x expected %x, PRU0 %u cycles, %u fps\r\n",
               image->name, crc, image->golden_crc, cycles, fps);
#else
    while (get32(ICSS_BASE + START_DONE) != 1U ||
           get32(ICSS_BASE + P1_BASE + 4U) != gFrame.blocks ||
           (get32(ICSS_BASE + PRU1_CONTROL) & PRU_RUNSTATE) != 0U) {
        if ((get32(ICSS_BASE + PRU0_CONTROL) & PRU_RUNSTATE) == 0U &&
            get32(ICSS_BASE + START_DONE) != 1U) {
            DebugP_log("%s: entropy decode error %x\r\n", image->name,
                       *(volatile uint8_t *)(uintptr_t)
                       (ICSS_BASE + DECODE_ERROR));
            goto stop;
        }
        if (ClockP_getTimeUsec() - began > JPEG_TIMEOUT_US) {
            DebugP_log("%s: timeout\r\n", image->name);
            goto stop;
        }
        ClockP_usleep(100);
    }
    if (*(volatile uint8_t *)(uintptr_t)(ICSS_BASE + DECODE_ERROR) != 0) {
        DebugP_log("%s: entropy decode error\r\n", image->name);
        goto stop;
    }
    uint32_t crc = crc32_memory(OUT_BASE, 64U*gFrame.blocks);
    uint32_t cycles0 = get32(ICSS_BASE + PRU0_CYCLE);
    uint32_t cycles1 = get32(ICSS_BASE + PRU1_CYCLE);
    uint32_t cycles = cycles0 > cycles1 ? cycles0 : cycles1;
    uint32_t fps = cycles ? PRU_CLOCK_HZ / cycles : 0;
    DebugP_log("%s: CRC %x expected %x, PRU0 %u cycles, PRU1 %u cycles, %u fps\r\n",
               image->name, crc, image->golden_crc, cycles0, cycles1, fps);
#endif
    if (crc != image->golden_crc) DebugP_log("%s: CRC mismatch\r\n", image->name);
stop:
    status = PRUICSS_disableCore(handle, PRUICSS_PRU0);
    DebugP_assert(status == SystemP_SUCCESS);
    status = PRUICSS_disableCore(handle, PRUICSS_PRU1);
    DebugP_assert(status == SystemP_SUCCESS);
}

void jpeg_host_main(void *args)
{
    (void)args;
    Drivers_open();
    int32_t status = Board_driversOpen();
    DebugP_assert(status == SystemP_SUCCESS);
    PRUICSS_Handle handle = PRUICSS_open(CONFIG_PRU_ICSS0);
    DebugP_assert(handle != NULL);
    for (uint32_t i = 0; i < gJpegImageCount; ++i) run_image(handle, &gJpegImages[i]);
    status = PRUICSS_close(handle);
    DebugP_assert(status == SystemP_SUCCESS);
    Board_driversClose();
    Drivers_close();
}
