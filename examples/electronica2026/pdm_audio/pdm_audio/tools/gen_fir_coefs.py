"""Generate firmware/fir_coefs.inc from stage2_fir_f32 in firmware/decimation_fir.h.

The 63-tap stage-2 FIR is scaled so a full-scale SINC3 input (+-OSR^3/2)
comes out as +-2^23 (24-bit PCM referenced to full scale), quantised to Q27,
padded to 64 taps and stored oldest-input first (T[j] = c'[63 - j], c'[63] = 0).
The include is PRU code that writes the table to PRU0 DRAM0 at the local
address held in r1 (the firmware loads r1 = FIR_T_BASE before the include).

Copied from pru-simulator source/pdm/tools/gen_fir_coefs.py (itself from
audio_pipe); only the default paths differ. The output is byte-identical
to the pru-simulator include, which its PCM reference reads
(pru-simulator tests/test_pdm_open_pru_port.py checks both).

Usage (from the project directory pdm_audio/pdm_audio):
    tools/gen_fir_coefs.py [--header firmware/decimation_fir.h]
                           [--out firmware/fir_coefs.inc] [--osr 96]
"""

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent / "firmware"    # pdm_audio/pdm_audio/firmware
TAPS = 64
Q = 27


def parse_taps(header_text):
    m = re.search(r"stage2_fir_f32\s*\[\s*STAGE2_TAPS\s*\]\s*=\s*\{(.*?)\};", header_text, re.S)
    if not m:
        raise ValueError("stage2_fir_f32 not found")
    taps = [float(v) for v in re.findall(r"[-+]?\d+\.\d+(?:[eE][-+]?\d+)?", m.group(1))]
    if len(taps) != 63:
        raise ValueError(f"expected 63 taps, found {len(taps)}")
    return taps


def table(taps, osr):
    scale = 2 ** 23 / (osr ** 3 / 2)
    c = [round(t * scale * 2 ** Q) for t in taps] + [0]
    for q in c:
        if not -2 ** 31 <= q < 2 ** 31:
            raise ValueError(f"coefficient {q} does not fit Q{Q} int32")
    return [c[TAPS - 1 - j] for j in range(TAPS)], scale


def render(taps, osr, source_name):
    t, scale = table(taps, osr)
    lines = [
        "; fir_coefs.inc -- GENERATED by tools/gen_fir_coefs.py, do not edit.",
        f"; Source: {source_name} (stage2_fir_f32, 63 taps, sum {sum(taps):.6f})",
        f"; OSR {osr}: scale 2^23 / (OSR^3 / 2) = {scale:.9f}; Q{Q}; 64 words to [r1] (PRU0 DRAM0),",
        "; oldest input first: T[j] = c'[63 - j], c'[63] = 0.",
        f"FIR_COEF_OSR        .set    {osr}",
    ]
    for j, q in enumerate(t):
        lines.append(f"    ldi32   r0, 0x{q & 0xFFFFFFFF:08x}              ; T[{j}] = {q}")
        lines.append(f"    sbbo    &r0, r1, {4 * j:#05x}, 4")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--header", default=str(HERE / "decimation_fir.h"))
    ap.add_argument("--out", default=str(HERE / "fir_coefs.inc"))
    ap.add_argument("--osr", type=int, default=96)
    a = ap.parse_args(argv)
    text = render(parse_taps(Path(a.header).read_text()), a.osr, Path(a.header).name)
    Path(a.out).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
